"""Erase the English name/quote printed on the parchment of large card pictures (tools/lg_src -> img/lg).
The French name is drawn over the clean parchment by CSS (see .lang-fr .card-lg::after)."""
import cv2, numpy as np, os, sys, shutil
src, dst = sys.argv[1], sys.argv[2]
os.makedirs(dst, exist_ok=True)
done = 0
ribbons = []
for f in sorted(os.listdir(src)):
    path = os.path.join(src, f)
    if f.startswith("faction_"):           # deck backs: no text
        shutil.copy(path, os.path.join(dst, f)); continue
    im = cv2.imread(path)
    h, w = im.shape[:2]
    y0, y1 = int(h * 0.768), int(h * 0.996)
    x0, x1 = int(w * 0.008), int(w * 0.992)
    roi = im[y0:y1, x0:x1]
    rh, rw = roi.shape[:2]
    hsv = cv2.cvtColor(roi, cv2.COLOR_BGR2HSV)
    gray = cv2.cvtColor(roi, cv2.COLOR_BGR2GRAY).astype(int)
    sat = hsv[..., 1].astype(int)
    ref = np.percentile(gray, 80)
    dark = (gray < ref - 32).astype(np.uint8)
    # keep the black rounded corners and the very bottom edge of the card
    cy, cx = np.mgrid[0:rh, 0:rw]
    ax, ay = cx + x0, cy + y0
    corner = ((ax < w * 0.07) | (ax > w * 0.93)) & (ay > h * 0.955)
    dark[corner] = 0
    # the shaded torn edge at the top of the parchment is not text (names start lower)
    dark[ay < h * 0.776] = 0
    # faction ribbon hanging over the parchment on the left (fixed position on the card template)
    protect = np.zeros((h, w), np.uint8)
    probe = im[int(h * 0.80): int(h * 0.865), int(w * 0.08): int(w * 0.16)]
    phsv = cv2.cvtColor(probe, cv2.COLOR_BGR2HSV).astype(int)
    pgray = cv2.cvtColor(probe, cv2.COLOR_BGR2GRAY).astype(int)
    ref_sat = np.median(hsv[..., 1])
    ref_hue = np.median(hsv[..., 0])
    hue_far = np.minimum(np.abs(phsv[..., 0] - ref_hue), 180 - np.abs(phsv[..., 0] - ref_hue)) > 25
    nonparch = (phsv[..., 1] > ref_sat + 45) | (pgray < ref - 50) | (hue_far & (phsv[..., 1] > 50))
    if nonparch.mean() > 0.6:
        ribbons.append(f[:-4])
        # the banner ends with a notch: lowest on both sides, highest in the middle
        poly = np.array([[w * 0.018, y0 - 2], [w * 0.232, y0 - 2], [w * 0.232, h * 0.862], [w * 0.212, h * 0.899],
                         [w * 0.127, h * 0.861], [w * 0.047, h * 0.897], [w * 0.018, h * 0.862]], np.int32)
        cv2.fillPoly(protect, [poly], 1)
    protect = protect[y0:y1, x0:x1]
    mask = dark & (1 - protect)
    mask = cv2.dilate(mask, np.ones((3, 3), np.uint8), iterations=2) & (1 - protect)
    full = np.zeros((h, w), np.uint8)
    full[y0:y1, x0:x1] = mask * 255
    out = cv2.inpaint(im, full, 4, cv2.INPAINT_TELEA)
    cv2.imwrite(os.path.join(dst, f), out, [cv2.IMWRITE_JPEG_QUALITY, 90])
    done += 1
import json
with open(os.path.join(os.path.dirname(os.path.abspath(dst)), "..", "card_ribbons.js"), "w") as fh:
    fh.write("// Generated by tools/clean_cards.py: large cards with a faction ribbon over the parchment\n")
    fh.write("const CARD_RIBBONS = new Set(" + json.dumps(sorted(ribbons)) + ");\n")
print("cleaned", done, "ribbons", len(ribbons))
