function t(key, ...args) {
	let s = I18N[LANG][key];
	if (s === undefined)
		s = I18N.en[key];
	if (s === undefined)
		return key;
	return s.replace(/\{(\d+)\}/g, (m, i) => args[Number(i)] !== undefined ? args[Number(i)] : m);
}

