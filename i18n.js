// Display name of a card (Card instance or card_dict data)
function cardName(card) {
	const name = card && card.name;
	if (!name)
		return "";
	if (LANG === "fr" && CARD_NAMES_FR[name] !== undefined)
		return CARD_NAMES_FR[name];
	return name.trim();
}

